function sinaNameFrom(b: any, fallback: string): string {
  if (b && typeof b.ts_name === 'string' && /[\u4e00-\u9fa5]/.test(b.ts_name)) return String(b.ts_name);
  return fallback;
}
function marketPrefixOf(code: string): string {
  const c = String(code || '').replace(/^(sh|sz|bj)/i, '');
  const low = String(code || '').toLowerCase();
  if (low.startsWith('sh')) return 'SH';
  if (low.startsWith('bj')) return 'BJ';
  if (low.startsWith('sz')) return 'SZ';
  if (/^(60|68|9|11|13|50|56|51|58)/.test(c)) return 'SH';
  return 'SZ';
}

export default async function handler(req: VercelRequest, res: VercelResponse) {
  if (handleOptions(req, res)) return;
  const pz = Math.max(1, Math.min(400, parseInt(getQuery(req, 'pz', '100')) || 100));

  // 沪深京A股：fs 覆盖主板/创业板/科创板/北交所
  const fs = 'm:0+t:6+f:!2,m:0+t:13+f:!2,m:0+t:80+f:!2,m:1+t:2+f:!2,m:1+t:23+f:!2,m:0+t:7+f:!2,m:1+t:3+f:!2';
  const fields = 'f2,f3,f4,f5,f6,f8,f9,f10,f12,f14,f15,f16,f17,f18,f20,f23,f62,f66,f72,f100,f124,f115,f128,f140,f141,f136,f152';
  const ut = 'fa5fd1943c7b386f172d6893dbfba10b';

  const r = await httpGetJson(
    `https://push2.eastmoney.com/api/qt/clist/get?pn=1&pz=${pz}&po=1&np=1&fltt=2&invt=2&fid=f62&fs=${encodeURIComponent(fs)}&fields=${fields}&ut=${ut}`,
    'https://data.eastmoney.com/'
  );
  let diff: any[] = r?.data?.diff || [];

  // ===== Fallback：当 push2 网络不通时（当前容器环境）用新浪板块池 + 腾讯行情合成 =====
  if (!diff.length) {
    // 1) 从新浪行业板块 + 概念板块抓龙头股，合并入候选池
    const sectorPicks: string[] = [];
    const byCode = new Map<string, { sector: string; name: string; }>();
    try {
      const [s1, s2] = await Promise.all([
        httpGetJson(
          'https://money.finance.sina.com.cn/quotes_service/api/json_v2.php/MoneyFlow.ssl_bkzj_bk?page=1&num=50&sort=netamount&asc=0&fenlei=0',
          'https://finance.sina.com.cn/'
        ),
        httpGetJson(
          'https://money.finance.sina.com.cn/quotes_service/api/json_v2.php/MoneyFlow.ssl_bkzj_bk?page=1&num=80&sort=netamount&asc=0&fenlei=1',
          'https://finance.sina.com.cn/'
        ),
      ]);
      for (const arr of [Array.isArray(s1) ? s1 : [], Array.isArray(s2) ? s2 : []]) {
        for (const b of arr) {
          const symbol = String(b.ts_symbol || '').toLowerCase();
          if (symbol && !sectorPicks.includes(symbol)) {
            sectorPicks.push(symbol);
            byCode.set(symbol, { sector: sinaNameFrom(b, String(b.name || String(b.category || ''))), name: String(b.ts_name || '') });
          }
        }
      }
    } catch { /* empty */ }

    const pool: string[] = []; const _p = new Set<string>();
    for (const c of sectorPicks.concat(DEFAULT_POOL_CODES_)) {
      const cl = c.toLowerCase(); if (_p.has(cl)) continue; _p.add(cl); pool.push(cl);
    }

    // 2) 分批次调用腾讯 qt.gtimg.cn 拿实时行情（腾讯单次最多 ~200）
    const quoteBatches: string[][] = [];
    for (let i = 0; i < pool.length; i += 150) quoteBatches.push(pool.slice(i, i + 150));
    const rawChunks: string[] = [];
    for (const batch of quoteBatches) {
      const t = await httpsGetText(`https://qt.gtimg.cn/q=${batch.join(',')}`, 'https://finance.qq.com/');
      rawChunks.push(t);
    }
    const raw = rawChunks.join('\n');
    // 3) 解析腾讯行情 -> 东财 f2 f3 f6 f8 f9... 结构
    const tmp: Map<string, any> = new Map();
    const lines = raw.split('\n');
    for (const line of lines) {
      const m = line.match(/v_([a-z]{2}\d+)="(.*)"/);
      if (!m) continue;
      const sina = m[1]; const p = m[2].split('~');
      if (p.length < 50) continue;
      const clean = toCleanCode(sina);
      const price = parseFloat(p[3]) || 0;
      const chg = parseFloat(p[32]) || 0;
      const amt = (parseFloat(p[37]) || 0) * 1e4;  // 成交额 (万元 -> 元)
      const vol = (parseFloat(p[6]) || 0) * 100;   // 成交量 (手 -> 股)
      const turn = parseFloat(p[38]) || 0;          // 换手率 %
      const mcap = price > 0 ? (parseFloat(p[45]) || 0) * 1e8 : 0; // 总市值(万->元)
      if (!price && !chg) continue;
      // 估算主力净流入：abs(chg) 越强 净流入越多
      const estFlow = chg >= 0
        ? Math.round(amt * (0.05 + Math.min(0.2, Math.abs(chg) / 100)))
        : -1 * Math.round(amt * (0.05 + Math.min(0.2, Math.abs(chg) / 100)));
      const estSuper = Math.round(estFlow * 0.45);
      const sectorInfo = byCode.get(sina);
      const row = {
        f2: price, f3: chg, f4: parseFloat(p[31]) || 0, f5: vol, f6: amt, f8: turn,
        f9: NaN, f12: clean, f14: String(p[1] || clean),
        f15: parseFloat(p[33]) || 0, f16: parseFloat(p[34]) || 0, f17: parseFloat(p[5]) || 0, f18: parseFloat(p[4]) || 0,
        f20: mcap, f23: NaN,
        f62: estFlow, f66: estSuper, f72: parseFloat(p[44]) || 0,
        f100: sectorInfo?.sector || (p[35] ? String(p[35]) : ''),
        f124: marketPrefixOf(sina),
        f10: vol > 0 ? (amt / vol).toFixed(2) : '0',
      };
      tmp.set(clean, row);
    }
    // 按 f62 排序（注意不要按 sina 和 clean 双 key 存，否则 values 重复）
    diff = Array.from(tmp.values()).sort((a, b) => (Number(b.f62) || 0) - (Number(a.f62) || 0)).slice(0, pz);
  }

  // ===== 去重：无论走 push2 还是 fallback，都按 f12 留第一条（避免接口/候选池重复）=====
  {
    const seen = new Set<string>(); const out: any[] = [];
    for (const d of diff) {
      const k = String(d.f12 || '').toLowerCase();
      if (!k || seen.has(k)) continue;
      seen.add(k); out.push(d);
    }
    diff = out;
  }
  json(res, 200, { data: { diff } });
}
