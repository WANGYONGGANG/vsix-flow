// ===== 综合生成器 =====
export function createBarrageGenerator(): {
  generate: () => BarrageEntry;
  update: (data: FundDataSnapshot) => void;
} {
  let snapshot: FundDataSnapshot = { sectors: [], totalFlow: 0, currentTime: '', dayHigh: 0, dayLow: 0 };

  return {
    update(newSnapshot: FundDataSnapshot) {
      snapshot = newSnapshot;
    },

    generate(): BarrageEntry {
      const user = USERNAMES[Math.floor(Math.random() * USERNAMES.length)];
      const now = new Date();
      const hour = now.getHours();
      const dayOfWeek = now.getDay();

      // 收集所有候选模板
      const candidates: { text: string; color: string; weight: number }[] = [];

      // 1. 板块资金 (权重 25)
      if (snapshot.sectors.length > 0) {
        const sorted = [...snapshot.sectors].sort((a, b) => Math.abs(b.value) - Math.abs(a.value));
        const top3 = sorted.slice(0, 3);
        for (const sector of top3) {
          const isPos = sector.value >= 0;
          const tpls = isPos ? sectorPosTpl(sector.name, sector.value) : sectorNegTpl(sector.name, sector.value);
          for (const t of tpls) {
            candidates.push({ text: t, color: randomColor(isPos ? COLORS.up : COLORS.down), weight: 25 });
          }
        }
      }

      // 2. 大盘分级 (权重 20)
      const totalFlow = snapshot.totalFlow;
      const flowCandidates = getTotalFlowGradeTpl(totalFlow);
      candidates.push(...flowCandidates);

      // 3. 大盘通用 (权重 12)
      const isUp = totalFlow >= 0;
      const indexTpls = isUp ? indexUpTpl(totalFlow) : indexDownTpl(totalFlow);
      for (const t of indexTpls) {
        candidates.push({ text: t, color: randomColor(isUp ? COLORS.up : COLORS.down), weight: 12 });
      }

      // 4. 时段 (权重 8)
      let timeTpls: string[] = [];
      if (hour < 11) timeTpls = MORNING_TPL;
      else if (hour < 13) timeTpls = NOON_TPL;
      else timeTpls = AFTERNOON_TPL;
      for (const t of timeTpls) {
        candidates.push({ text: t, color: randomColor(COLORS.cyan), weight: 8 });
      }

      // 5. 周几 (权重 8)
      let dayTpls: string[] = [];
      if (dayOfWeek === 0 || dayOfWeek === 6) dayTpls = WEEKEND_TPL;
      else if (dayOfWeek === 1) dayTpls = MONDAY_TPL;
      else if (dayOfWeek === 2) dayTpls = TUESDAY_TPL;
      else if (dayOfWeek === 3) dayTpls = WEDNESDAY_TPL;
      else if (dayOfWeek === 4) dayTpls = THURSDAY_TPL;
      else if (dayOfWeek === 5) dayTpls = FRIDAY_TPL;
      for (const t of dayTpls) {
        candidates.push({ text: t, color: randomColor(COLORS.teal), weight: 8 });
      }

      // 6. 日期/月份感知 (权重 8)
      const dateTpls = getDateContextTpl(now);
      for (const t of dateTpls) {
        candidates.push({ text: t, color: randomColor(COLORS.sky), weight: 8 });
      }

      // 7. 日内位置 (权重 12)
      const posCandidates = getPositionTpl(totalFlow, snapshot.dayHigh, snapshot.dayLow);
      candidates.push(...posCandidates);

      // 8. 板块异动分级 (权重 18)
      const abnormalCandidates = getSectorAbnormalTpl(snapshot.sectors);
      candidates.push(...abnormalCandidates);

      // 9. 成交量 (权重 6)
      const volCandidates = getVolumeTpl(snapshot.sectors);
      candidates.push(...volCandidates);

      // 10. 涨停跌停 (权重 5)
      const limitCandidates = getLimitTpl(totalFlow);
      candidates.push(...limitCandidates);

      // 11. 北向资金 (权重 5)
      const northCandidates = getNorthTpl(totalFlow);
      candidates.push(...northCandidates);

      // 12. 历史点位 (权重 8)
      const historyCandidates = getHistoryTpl(totalFlow, snapshot.dayHigh, snapshot.dayLow);
      candidates.push(...historyCandidates);

      // 13. 突破/支撑 (权重 8)
      if (snapshot.dayHigh > 0 && snapshot.dayLow > 0) {
        const mid = (snapshot.dayHigh + snapshot.dayLow) / 2;
        const totalAbs = Math.abs(totalFlow);
        if (totalAbs > mid * 0.8) {
          for (const t of BREAKOUT_TPL) {
            candidates.push({ text: t('日内高点'), color: randomColor(COLORS.gold), weight: 8 });
          }
        } else if (totalAbs < mid * 0.2) {
          for (const t of SUPPORT_TPL) {
            candidates.push({ text: t('日内低点'), color: randomColor(COLORS.purple), weight: 8 });
          }
        }
      }

      // 14. 均线 (权重 4)
      const maCandidates = getMATpl();
      candidates.push(...maCandidates);

      // 15. 政策/消息 (权重 3)
      const policyCandidates = getPolicyTpl();
      candidates.push(...policyCandidates);

      // 16. 资金流向细节 (权重 3)
      const flowDetailCandidates = getFlowDetailTpl();
      candidates.push(...flowDetailCandidates);

      // 17. 情绪/心态 (权重 3)
      const emotionCandidates = getEmotionTpl();
      candidates.push(...emotionCandidates);

      // 18. 闲聊 (权重 2)
      for (const t of CHAT_TPL) {
        candidates.push({ text: t, color: randomColor(COLORS.blue), weight: 2 });
      }

      if (candidates.length === 0) {
        return { text: CHAT_TPL[0], color: COLORS.blue, user };
      }

      // 按权重加权随机选择
      const totalWeight = candidates.reduce((s, c) => s + c.weight, 0);
      let rand = Math.random() * totalWeight;
      for (const c of candidates) {
        rand -= c.weight;
        if (rand <= 0) {
          return { text: c.text, color: c.color, user };
        }
      }
      return { text: candidates[0].text, color: candidates[0].color, user };
    },
  };
}

